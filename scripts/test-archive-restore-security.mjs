import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

const migration = await readFile(new URL(
  '../supabase/migrations/20260726143000_secure_archive_restore_queue.sql',
  import.meta.url,
), 'utf8');
const db = new PGlite();
const ownerA = '11111111-1111-4111-8111-111111111111';
const ownerB = '22222222-2222-4222-8222-222222222222';
const developer = '33333333-3333-4333-8333-333333333333';

await db.exec(`
  CREATE ROLE anon NOLOGIN;
  CREATE ROLE authenticated NOLOGIN;
  CREATE ROLE service_role NOLOGIN;
  CREATE SCHEMA auth;
  CREATE SCHEMA private;
  CREATE TABLE auth.users(id uuid PRIMARY KEY);
  CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
    SELECT (NULLIF(current_setting('request.jwt.claims', true), '')::jsonb ->> 'sub')::uuid;
  $$;
  CREATE FUNCTION auth.jwt() RETURNS jsonb LANGUAGE sql STABLE AS $$
    SELECT COALESCE(NULLIF(current_setting('request.jwt.claims', true), '')::jsonb, '{}'::jsonb);
  $$;
  CREATE TABLE public.internal_staff(
    user_id uuid PRIMARY KEY REFERENCES auth.users(id),
    role text NOT NULL,
    status text NOT NULL,
    display_name text
  );
  CREATE TABLE public.internal_access_events(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id uuid,
    actor_role text,
    action text NOT NULL,
    target_type text,
    target_id text,
    result text NOT NULL CHECK (result IN ('allowed','denied','failed')),
    reason text,
    metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
  );
  CREATE TABLE public.configuracoes(
    id text PRIMARY KEY,
    valor jsonb,
    "atualizadoEm" timestamptz
  );
  CREATE TABLE public.vistorias(
    id text PRIMARY KEY,
    protocolo text,
    municipio text,
    "nivelRisco" text,
    "dataVistoria" timestamptz,
    storage_location text NOT NULL DEFAULT 'supabase',
    drive_folder_url text,
    drive_file_ids jsonb,
    archived_at timestamptz,
    "fotosUrls" text[]
  );
  CREATE FUNCTION private.current_internal_role(p_user_id uuid DEFAULT auth.uid())
  RETURNS text LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
    SELECT role FROM public.internal_staff WHERE user_id = p_user_id AND status = 'active';
  $$;
  CREATE FUNCTION private.has_internal_permission(p_permission text, p_user_id uuid DEFAULT auth.uid())
  RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
    SELECT private.current_internal_role(p_user_id) = 'owner' AND p_permission = 'configuration.publish';
  $$;
  CREATE FUNCTION private.has_aal2() RETURNS boolean LANGUAGE sql STABLE SET search_path = '' AS $$
    SELECT COALESCE(auth.jwt()->>'aal', 'aal1') = 'aal2';
  $$;
  CREATE FUNCTION private.sanitize_internal_metadata(p_metadata jsonb)
  RETURNS jsonb LANGUAGE sql IMMUTABLE SET search_path = '' AS $$
    SELECT COALESCE(p_metadata, '{}'::jsonb);
  $$;
  CREATE FUNCTION private.set_internal_updated_at() RETURNS trigger
  LANGUAGE plpgsql SET search_path = '' AS $$
  BEGIN NEW.updated_at := now(); RETURN NEW; END;
  $$;
  INSERT INTO auth.users(id) VALUES ('${ownerA}'),('${ownerB}'),('${developer}');
  INSERT INTO public.internal_staff VALUES
    ('${ownerA}','owner','active','Owner A'),
    ('${ownerB}','owner','active','Owner B'),
    ('${developer}','developer','active','Developer');
  INSERT INTO public.configuracoes VALUES
    ('arquivamento','{"mode":"manual","enabled":true,"days_threshold":7}',now());
  INSERT INTO public.vistorias(
    id,protocolo,municipio,"nivelRisco","dataVistoria",storage_location,
    drive_folder_url,drive_file_ids,archived_at
  ) VALUES
    ('inspection-1','TCS-001','Campinas','R2',now()-interval '30 days','drive',
      'https://drive.google.com/drive/folders/folder-1','{"laudo":"file-1"}',now()),
    ('inspection-2','TCS-002','Santos','R3',now()-interval '40 days','drive',
      'https://drive.google.com/drive/folders/folder-2','{"laudo":"file-2"}',now()),
    ('inspection-3','TCS-003','Santos','R1',now()-interval '50 days','drive',
      'https://drive.google.com/drive/folders/folder-3','{"laudo":"file-3"}',now());
`);

try {
  await db.exec(migration);

  await db.query(`SELECT set_config('request.jwt.claims',$1,false)`, [
    JSON.stringify({ sub: ownerA, aal: 'aal1', role: 'authenticated' }),
  ]);
  await assert.rejects(() => db.query(
    `SELECT public.request_internal_archive_restore(ARRAY['inspection-1'],'Motivo seguro de teste',$1)`,
    [crypto.randomUUID()],
  ), /aal2_required/);

  await db.query(`SELECT set_config('request.jwt.claims',$1,false)`, [
    JSON.stringify({ sub: developer, aal: 'aal2', role: 'authenticated' }),
  ]);
  await assert.rejects(() => db.query(
    `SELECT public.request_internal_archive_restore(ARRAY['inspection-1'],'Motivo seguro de teste',$1)`,
    [crypto.randomUUID()],
  ), /archive_restore_not_allowed/);

  await db.query(`SELECT set_config('request.jwt.claims',$1,false)`, [
    JSON.stringify({ sub: ownerA, aal: 'aal2', role: 'authenticated' }),
  ]);
  const single = await db.query(
    `SELECT public.request_internal_archive_restore(ARRAY['inspection-1'],'Atendimento administrativo',$1) result`,
    [crypto.randomUUID()],
  );
  assert.equal(single.rows[0].result.status, 'approved');
  assert.equal(single.rows[0].result.requires_second_approval, false);

  const batch = await db.query(
    `SELECT public.request_internal_archive_restore(ARRAY['inspection-2','inspection-3'],'Auditoria solicitou o lote',$1) result`,
    [crypto.randomUUID()],
  );
  assert.equal(batch.rows[0].result.status, 'pending');
  assert.equal(batch.rows[0].result.requires_second_approval, true);
  const batchRequestId = batch.rows[0].result.request_ids[0];
  await assert.rejects(() => db.query(
    `SELECT public.decide_internal_archive_restore($1,true,'Aprovação do próprio lote')`,
    [batchRequestId],
  ), /second_owner_required/);

  await db.query(`SELECT set_config('request.jwt.claims',$1,false)`, [
    JSON.stringify({ sub: ownerB, aal: 'aal2', role: 'authenticated' }),
  ]);
  const approval = await db.query(
    `SELECT public.decide_internal_archive_restore($1,true,'Segunda aprovação independente') result`,
    [batchRequestId],
  );
  assert.equal(approval.rows[0].result.status, 'approved');
  assert.equal(approval.rows[0].result.request_ids.length, 2);
  await db.query(`SELECT public.claim_internal_archive_restore($1)`, [batchRequestId]);

  await db.query(`SELECT set_config('request.jwt.claims',$1,false)`, [
    JSON.stringify({ sub: ownerB, aal: 'aal2', role: 'service_role' }),
  ]);
  await db.query(
    `SELECT public.finalize_archive_restore_internal($1,$2,'[{"bucket":"laudos","path":"Santos/inspection-2.pdf","sha256":"abc"}]')`,
    [batchRequestId, ownerB],
  );
  const restored = await db.query(`
    SELECT r.status, v.storage_location, count(e.id)::integer AS audit_events
    FROM public.archive_restore_requests r
    JOIN public.vistorias v ON v.id = r.inspection_id
    LEFT JOIN public.internal_access_events e ON e.target_id = r.id::text
    WHERE r.id = $1
    GROUP BY r.status,v.storage_location
  `, [batchRequestId]);
  assert.deepEqual(restored.rows[0], {
    status: 'restored',
    storage_location: 'supabase',
    audit_events: 4,
  });

  console.log('Restauração: MFA, permissão, idempotência, dupla aprovação, transação e auditoria validados.');
} finally {
  await db.close();
}
