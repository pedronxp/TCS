CREATE OR REPLACE FUNCTION private.internal_permissions(p_role text)
RETURNS text[]
LANGUAGE sql IMMUTABLE
SET search_path = ''
AS $$
  SELECT CASE p_role
    WHEN 'owner' THEN ARRAY[
      'console.read', 'dashboard.executive.read', 'customer.read', 'customer.sensitive.read',
      'customer.write', 'commercial.read', 'commercial.write', 'support.read', 'support.write',
      'session.read', 'session.terminate', 'staff.read', 'staff.manage', 'audit.read',
      'technical.read', 'technical.write', 'build.request', 'build.approve', 'configuration.publish'
    ]::text[]
    WHEN 'developer' THEN ARRAY[
      'console.read', 'dashboard.technical.read', 'customer.read', 'customer.sensitive.request',
      'commercial.read', 'support.read', 'support.write', 'session.read', 'session.terminate',
      'audit.read', 'technical.read', 'technical.write', 'build.request', 'configuration.prepare'
    ]::text[]
    WHEN 'support' THEN ARRAY[]::text[]
    WHEN 'auditor' THEN ARRAY[]::text[]
    ELSE ARRAY[]::text[]
  END;
$$;

CREATE OR REPLACE FUNCTION private.current_internal_role(p_user_id uuid DEFAULT auth.uid())
RETURNS text
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT s.role
  FROM public.internal_staff s
  WHERE s.user_id = p_user_id AND s.status = 'active'
  LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION private.has_internal_permission(
  p_permission text,
  p_user_id uuid DEFAULT auth.uid()
)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT p_user_id IS NOT NULL
    AND p_permission = ANY(
      private.internal_permissions(private.current_internal_role(p_user_id))
    );
$$;

CREATE OR REPLACE FUNCTION private.has_aal2()
RETURNS boolean
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT COALESCE(auth.jwt()->>'aal', 'aal1') = 'aal2';
$$;

CREATE OR REPLACE FUNCTION private.sanitize_internal_metadata(p_metadata jsonb)
RETURNS jsonb
LANGUAGE sql IMMUTABLE
SET search_path = ''
AS $$
  SELECT COALESCE(p_metadata, '{}'::jsonb) - ARRAY[
    'token', 'access_token', 'refresh_token', 'authorization', 'password', 'secret',
    'api_key', 'service_role', 'cpf', 'document', 'email', 'phone', 'photo', 'content'
  ]::text[];
$$;

