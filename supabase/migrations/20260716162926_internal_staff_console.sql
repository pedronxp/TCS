CREATE OR REPLACE FUNCTION public.request_internal_build(
  p_operation_id uuid,
  p_provider text,
  p_environment text,
  p_version text,
  p_profile text,
  p_changelog text,
  p_reason text
)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE request public.internal_build_requests; initial_status text;
BEGIN
  IF NOT private.has_internal_permission('build.request') THEN
    RAISE EXCEPTION 'build_request_not_allowed' USING ERRCODE = '42501';
  END IF;
  IF NOT private.has_aal2() THEN RAISE EXCEPTION 'aal2_required' USING ERRCODE = '42501'; END IF;
  IF p_environment NOT IN ('development', 'preview', 'production') THEN RAISE EXCEPTION 'invalid_environment'; END IF;
  IF char_length(trim(p_reason)) < 8 THEN RAISE EXCEPTION 'reason_required'; END IF;
  initial_status := CASE WHEN p_environment = 'production' THEN 'pending' ELSE 'approved' END;

  INSERT INTO public.internal_build_requests(
    operation_id, requested_by, provider, environment, version, profile,
    changelog, reason, status
  ) VALUES (
    p_operation_id, auth.uid(), p_provider, p_environment, left(p_version, 50),
    left(p_profile, 50), left(COALESCE(p_changelog, ''), 5000), trim(p_reason), initial_status
  )
  ON CONFLICT (requested_by, operation_id) DO UPDATE
    SET operation_id = EXCLUDED.operation_id
  RETURNING * INTO request;

  INSERT INTO public.internal_access_events(
    actor_id, actor_role, action, target_type, target_id, result, reason, metadata
  ) VALUES (
    auth.uid(), private.current_internal_role(), 'build.request', 'build_request',
    request.id::text, 'allowed', left(p_reason, 500),
    jsonb_build_object('environment', request.environment, 'status', request.status, 'version', request.version)
  );
  RETURN jsonb_build_object('ok', true, 'request_id', request.id, 'status', request.status);
END;
$$;

CREATE OR REPLACE FUNCTION public.decide_internal_build(
  p_request_id uuid,
  p_approve boolean,
  p_reason text
)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE request public.internal_build_requests;
BEGIN
  IF NOT private.has_internal_permission('build.approve') THEN
    RAISE EXCEPTION 'build_approval_not_allowed' USING ERRCODE = '42501';
  END IF;
  IF NOT private.has_aal2() THEN RAISE EXCEPTION 'aal2_required' USING ERRCODE = '42501'; END IF;
  IF char_length(trim(p_reason)) < 8 THEN RAISE EXCEPTION 'reason_required'; END IF;

  SELECT * INTO request FROM public.internal_build_requests WHERE id = p_request_id FOR UPDATE;
  IF request.id IS NULL OR request.status <> 'pending' THEN RAISE EXCEPTION 'build_request_not_pending'; END IF;
  IF request.requested_by = auth.uid() THEN RAISE EXCEPTION 'self_approval_not_allowed' USING ERRCODE = '42501'; END IF;

  UPDATE public.internal_build_requests
  SET status = CASE WHEN p_approve THEN 'approved' ELSE 'rejected' END,
      approved_by = auth.uid(), decided_at = now()
  WHERE id = p_request_id
  RETURNING * INTO request;

  INSERT INTO public.internal_access_events(
    actor_id, actor_role, action, target_type, target_id, result, reason, metadata
  ) VALUES (
    auth.uid(), private.current_internal_role(), 'build.decide', 'build_request',
    request.id::text, 'allowed', left(p_reason, 500),
    jsonb_build_object('status', request.status, 'environment', request.environment, 'version', request.version)
  );
  RETURN jsonb_build_object('ok', true, 'request_id', request.id, 'status', request.status);
END;
$$;

-- Remote session termination is a high-risk action for internal staff.
CREATE OR REPLACE FUNCTION public.end_active_session(
  p_session_id uuid,
  p_reason text DEFAULT 'remote_termination'
)
RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE target public.active_sessions; actor uuid := auth.uid(); internal_role text;
BEGIN
  SELECT * INTO target FROM public.active_sessions WHERE id = p_session_id FOR UPDATE;
  IF target.id IS NULL THEN RETURN false; END IF;
  internal_role := private.current_internal_role(actor);

  IF internal_role IS NOT NULL THEN
    IF NOT private.has_internal_permission('session.terminate', actor) THEN
      RAISE EXCEPTION 'session_termination_not_allowed' USING ERRCODE = '42501';
    END IF;
    IF target.user_id <> actor AND NOT private.has_aal2() THEN
      RAISE EXCEPTION 'aal2_required' USING ERRCODE = '42501';
    END IF;
    IF target.user_id <> actor AND char_length(trim(p_reason)) < 8 THEN
      RAISE EXCEPTION 'reason_required';
    END IF;
  ELSIF target.user_id <> actor
    AND NOT private.is_owner_admin(actor)
    AND NOT (
      target.organization_id = private.current_organization_id(actor)
      AND private.organization_role(target.organization_id, actor) IN ('owner', 'coordinator', 'supervisor')
    ) THEN
    RAISE EXCEPTION 'session_termination_not_allowed' USING ERRCODE = '42501';
  END IF;

  UPDATE public.active_sessions
  SET status = 'revoked', ended_at = now(), ended_by = actor, end_reason = left(trim(p_reason), 200)
  WHERE id = p_session_id AND status = 'active';

  INSERT INTO public.subscription_audit_events(
    organization_id, actor_id, event_type, entity_type, entity_id, metadata
  ) VALUES (
    target.organization_id, actor, 'session_ended', 'active_session', p_session_id::text,
    jsonb_build_object('reason', left(trim(p_reason), 200))
  );
  IF internal_role IS NOT NULL THEN
    INSERT INTO public.internal_access_events(
      actor_id, actor_role, action, target_type, target_id, result, reason
    ) VALUES (actor, internal_role, 'session.terminate', 'active_session', p_session_id::text, 'allowed', left(trim(p_reason), 500));
  END IF;
  RETURN true;
END;
$$;

