CREATE OR REPLACE FUNCTION public.get_internal_staff_profile()
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE staff public.internal_staff;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'authentication_required' USING ERRCODE = '42501';
  END IF;

  SELECT * INTO staff
  FROM public.internal_staff
  WHERE user_id = auth.uid() AND status = 'active';

  IF staff.id IS NULL THEN RETURN NULL; END IF;

  RETURN jsonb_build_object(
    'id', staff.id,
    'user_id', staff.user_id,
    'role', staff.role,
    'status', staff.status,
    'display_name', staff.display_name,
    'permissions', to_jsonb(private.internal_permissions(staff.role)),
    'assurance_level', COALESCE(auth.jwt()->>'aal', 'aal1')
  );
END;
$$;

