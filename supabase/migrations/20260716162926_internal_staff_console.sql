-- Internal console identities and authorization boundaries.
-- The legacy owner_admins gate remains available while VITE_INTERNAL_CONSOLE_V2
-- is in pilot, but every new internal operation uses internal_staff.

CREATE SCHEMA IF NOT EXISTS private;
REVOKE ALL ON SCHEMA private FROM PUBLIC, anon;

CREATE TABLE public.internal_staff (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
  role text NOT NULL CHECK (role IN ('owner', 'developer', 'support', 'auditor')),
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended', 'removed')),
  display_name text,
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX internal_staff_role_status_idx ON public.internal_staff(role, status);

CREATE TABLE public.internal_access_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  actor_role text,
  action text NOT NULL,
  target_type text,
  target_id text,
  result text NOT NULL CHECK (result IN ('allowed', 'denied', 'failed')),
  reason text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX internal_access_events_actor_created_idx
  ON public.internal_access_events(actor_id, created_at DESC);
CREATE INDEX internal_access_events_target_created_idx
  ON public.internal_access_events(target_type, target_id, created_at DESC);

CREATE TABLE public.internal_sensitive_access (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  staff_user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  customer_key text NOT NULL CHECK (customer_key ~ '^(organization|user):[0-9a-f-]{36}$'),
  ticket_id uuid NOT NULL REFERENCES public.support_tickets(id) ON DELETE CASCADE,
  reason text NOT NULL CHECK (char_length(trim(reason)) BETWEEN 8 AND 500),
  granted_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  CHECK (expires_at > granted_at)
);
CREATE INDEX internal_sensitive_access_active_idx
  ON public.internal_sensitive_access(staff_user_id, customer_key, expires_at DESC)
  WHERE revoked_at IS NULL;

CREATE TABLE public.internal_operations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  operation_id uuid NOT NULL,
  actor_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  action text NOT NULL,
  request_hash text NOT NULL,
  status text NOT NULL DEFAULT 'processing' CHECK (status IN ('processing', 'succeeded', 'failed')),
  result jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  UNIQUE (actor_id, operation_id)
);
CREATE INDEX internal_operations_created_idx ON public.internal_operations(created_at DESC);

CREATE TABLE public.technical_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_key uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  organization_id uuid REFERENCES public.organizations(id) ON DELETE SET NULL,
  user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  app_version text,
  platform text NOT NULL CHECK (platform IN ('android', 'ios', 'web', 'server', 'unknown')),
  category text NOT NULL CHECK (category IN ('version', 'build', 'sync', 'storage', 'runtime', 'configuration')),
  severity text NOT NULL CHECK (severity IN ('debug', 'info', 'warning', 'error', 'critical')),
  correlation_id text,
  summary text NOT NULL CHECK (char_length(summary) BETWEEN 1 AND 500),
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(metadata) = 'object'),
  occurred_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX technical_events_filters_idx
  ON public.technical_events(category, severity, occurred_at DESC);
CREATE INDEX technical_events_org_occurred_idx
  ON public.technical_events(organization_id, occurred_at DESC);
CREATE INDEX technical_events_version_platform_idx
  ON public.technical_events(app_version, platform, occurred_at DESC);
CREATE INDEX technical_events_correlation_idx
  ON public.technical_events(correlation_id) WHERE correlation_id IS NOT NULL;

CREATE TABLE public.internal_build_requests (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  operation_id uuid NOT NULL,
  requested_by uuid NOT NULL REFERENCES auth.users(id),
  approved_by uuid REFERENCES auth.users(id),
  provider text NOT NULL CHECK (provider IN ('eas', 'github')),
  environment text NOT NULL CHECK (environment IN ('development', 'preview', 'production')),
  version text NOT NULL,
  profile text NOT NULL,
  changelog text NOT NULL DEFAULT '',
  reason text NOT NULL CHECK (char_length(trim(reason)) BETWEEN 8 AND 500),
  status text NOT NULL CHECK (status IN ('pending', 'approved', 'rejected', 'executed', 'failed')),
  created_at timestamptz NOT NULL DEFAULT now(),
  decided_at timestamptz,
  executed_at timestamptz,
  UNIQUE (requested_by, operation_id),
  CHECK (approved_by IS NULL OR approved_by <> requested_by)
);
CREATE INDEX internal_build_requests_status_created_idx
  ON public.internal_build_requests(status, created_at DESC);

