CREATE OR REPLACE FUNCTION private.can_access_sensitive_customer(
  p_customer_key text,
  p_user_id uuid DEFAULT auth.uid()
)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT private.has_internal_permission('customer.sensitive.read', p_user_id)
    OR EXISTS (
      SELECT 1
      FROM public.internal_sensitive_access a
      WHERE a.staff_user_id = p_user_id
        AND a.customer_key = p_customer_key
        AND a.revoked_at IS NULL
        AND a.expires_at > now()
    );
$$;

