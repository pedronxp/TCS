CREATE OR REPLACE FUNCTION public.manage_internal_staff(
  p_user_id uuid,
  p_role text,
  p_status text,
  p_reason text,
  p_operation_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  actor uuid := auth.uid();
  previous public.internal_staff;
  updated public.internal_staff;
  previous_result jsonb;
  v_request_hash text;
BEGIN
  IF NOT private.has_internal_permission('staff.manage', actor) THEN
    RAISE EXCEPTION 'staff_management_not_allowed' USING ERRCODE = '42501';
  END IF;
  IF NOT private.has_aal2() THEN
    RAISE EXCEPTION 'aal2_required' USING ERRCODE = '42501';
  END IF;
  IF p_role NOT IN ('owner', 'developer') OR p_status NOT IN ('active', 'suspended', 'removed') THEN
    RAISE EXCEPTION 'invalid_staff_state';
  END IF;
  IF char_length(trim(p_reason)) < 8 THEN RAISE EXCEPTION 'reason_required'; END IF;

  v_request_hash := md5(concat_ws('|', p_user_id, p_role, p_status, trim(p_reason)));
  SELECT result INTO previous_result
  FROM public.internal_operations
  WHERE actor_id = actor AND operation_id = p_operation_id AND request_hash = v_request_hash;
  IF previous_result IS NOT NULL THEN RETURN previous_result; END IF;

  INSERT INTO public.internal_operations(operation_id, actor_id, action, request_hash)
  VALUES (p_operation_id, actor, 'staff.manage', v_request_hash);

  SELECT * INTO previous FROM public.internal_staff WHERE user_id = p_user_id FOR UPDATE;
  INSERT INTO public.internal_staff(user_id, role, status, created_by)
  VALUES (p_user_id, p_role, p_status, actor)
  ON CONFLICT (user_id) DO UPDATE SET role = EXCLUDED.role, status = EXCLUDED.status
  RETURNING * INTO updated;

  previous_result := jsonb_build_object('ok', true, 'staff', to_jsonb(updated));
  UPDATE public.internal_operations
  SET status = 'succeeded', result = previous_result, completed_at = now()
  WHERE actor_id = actor AND operation_id = p_operation_id;

  INSERT INTO public.internal_access_events(
    actor_id, actor_role, action, target_type, target_id, result, reason, metadata
  ) VALUES (
    actor, private.current_internal_role(actor), 'staff.manage', 'internal_staff',
    p_user_id::text, 'allowed', left(p_reason, 500),
    jsonb_build_object(
      'before', CASE WHEN previous.id IS NULL THEN NULL ELSE jsonb_build_object('role', previous.role, 'status', previous.status) END,
      'after', jsonb_build_object('role', updated.role, 'status', updated.status)
    )
  );
  RETURN previous_result;
EXCEPTION WHEN unique_violation THEN
  SELECT result INTO previous_result
  FROM public.internal_operations
  WHERE actor_id = actor AND operation_id = p_operation_id;
  IF previous_result IS NOT NULL THEN RETURN previous_result; END IF;
  RAISE;
END;
$$;

CREATE OR REPLACE FUNCTION public.request_sensitive_support_access(
  p_customer_key text,
  p_ticket_id uuid,
  p_reason text
)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE ticket public.support_tickets; access_id uuid;
BEGIN
  IF NOT private.has_internal_permission('customer.sensitive.request') THEN
    RAISE EXCEPTION 'sensitive_access_not_allowed' USING ERRCODE = '42501';
  END IF;
  IF NOT private.has_aal2() THEN
    RAISE EXCEPTION 'aal2_required' USING ERRCODE = '42501';
  END IF;
  IF char_length(trim(p_reason)) < 8 THEN RAISE EXCEPTION 'reason_required'; END IF;

  SELECT * INTO ticket FROM public.support_tickets WHERE id = p_ticket_id;
  IF ticket.id IS NULL OR ticket.status NOT IN ('open', 'in_progress', 'waiting_customer') THEN
    RAISE EXCEPTION 'active_support_ticket_required' USING ERRCODE = '42501';
  END IF;
  IF p_customer_key <> COALESCE('organization:' || ticket.organization_id::text, 'user:' || ticket.user_id::text) THEN
    RAISE EXCEPTION 'ticket_customer_mismatch' USING ERRCODE = '42501';
  END IF;

  INSERT INTO public.internal_sensitive_access(
    staff_user_id, customer_key, ticket_id, reason, expires_at
  ) VALUES (auth.uid(), p_customer_key, p_ticket_id, trim(p_reason), now() + interval '60 minutes')
  RETURNING id INTO access_id;

  INSERT INTO public.internal_access_events(
    actor_id, actor_role, action, target_type, target_id, result, reason,
    metadata
  ) VALUES (
    auth.uid(), private.current_internal_role(), 'customer.sensitive.access',
    'customer', p_customer_key, 'allowed', left(p_reason, 500),
    jsonb_build_object('ticket_id', p_ticket_id, 'access_id', access_id, 'expires_in_minutes', 60)
  );
  RETURN jsonb_build_object('ok', true, 'access_id', access_id, 'expires_in_minutes', 60);
END;
$$;

CREATE OR REPLACE FUNCTION public.ingest_technical_event(
  p_event_key uuid,
  p_organization_id uuid,
  p_app_version text,
  p_platform text,
  p_category text,
  p_severity text,
  p_correlation_id text,
  p_summary text,
  p_metadata jsonb DEFAULT '{}'::jsonb
)
RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE event_id bigint;
BEGIN
  IF NOT private.has_internal_permission('technical.write') THEN
    RAISE EXCEPTION 'technical_event_not_allowed' USING ERRCODE = '42501';
  END IF;
  INSERT INTO public.technical_events(
