CREATE OR REPLACE FUNCTION public.list_internal_customers(
  p_search text DEFAULT NULL,
  p_status text DEFAULT NULL,
  p_limit integer DEFAULT 25,
  p_offset integer DEFAULT 0
)
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE result jsonb;
BEGIN
  IF NOT private.has_internal_permission('customer.read') THEN
    RAISE EXCEPTION 'customer_read_not_allowed' USING ERRCODE = '42501';
  END IF;

  WITH customers AS (
    SELECT
      'organization:' || o.id::text AS customer_id,
      'organization'::text AS kind,
      o.id AS subject_id,
      o.display_name,
      o.legal_name,
      o.municipality_name,
      o.state_code,
      o.status,
      CASE WHEN private.current_internal_role() = 'owner' THEN o.contact_name END AS contact_name,
      CASE WHEN private.current_internal_role() = 'owner' THEN o.contact_email END AS contact_email,
      s.status AS subscription_status,
      p.name AS plan_name,
      (SELECT count(*)::integer FROM public.organization_members m WHERE m.organization_id = o.id AND m.status = 'active') AS active_users,
      o.updated_at AS last_activity_at
    FROM public.organizations o
    LEFT JOIN LATERAL (
      SELECT sub.* FROM public.subscriptions sub
      WHERE sub.organization_id = o.id
      ORDER BY sub.created_at DESC LIMIT 1
    ) s ON true
    LEFT JOIN public.plans p ON p.id = s.plan_id
    UNION ALL
    SELECT
      'user:' || u.uid::text,
      'individual'::text,
      u.uid,
      COALESCE(NULLIF(trim(u.name), ''), 'Conta individual'),
      NULL::text,
      u.municipio,
      NULL::text,
      CASE WHEN u."isApproved" THEN 'active' ELSE 'onboarding' END,
      NULL::text,
      CASE WHEN private.current_internal_role() = 'owner' THEN u.email END,
      s.status,
      p.name,
      1,
      u."createdAt"
    FROM public.users u
    LEFT JOIN LATERAL (
      SELECT sub.* FROM public.subscriptions sub
      WHERE sub.user_id = u.uid
      ORDER BY sub.created_at DESC LIMIT 1
    ) s ON true
    LEFT JOIN public.plans p ON p.id = s.plan_id
    WHERE u.organization_id IS NULL AND u.role <> 'master_admin'
  ), filtered AS (
    SELECT * FROM customers c
    WHERE (p_status IS NULL OR p_status = '' OR c.status = p_status)
      AND (
        p_search IS NULL OR trim(p_search) = ''
        OR c.display_name ILIKE '%' || trim(p_search) || '%'
        OR COALESCE(c.legal_name, '') ILIKE '%' || trim(p_search) || '%'
        OR COALESCE(c.municipality_name, '') ILIKE '%' || trim(p_search) || '%'
        OR COALESCE(c.contact_name, '') ILIKE '%' || trim(p_search) || '%'
        OR COALESCE(c.contact_email, '') ILIKE '%' || trim(p_search) || '%'
        OR c.customer_id ILIKE '%' || trim(p_search) || '%'
      )
  ), page AS (
    SELECT * FROM filtered
    ORDER BY display_name, customer_id
    LIMIT greatest(1, least(p_limit, 100)) OFFSET greatest(p_offset, 0)
  )
  SELECT jsonb_build_object(
    'items', COALESCE((SELECT jsonb_agg(to_jsonb(page)) FROM page), '[]'::jsonb),
    'total', (SELECT count(*) FROM filtered),
    'limit', greatest(1, least(p_limit, 100)),
    'offset', greatest(p_offset, 0)
  ) INTO result;
  RETURN result;
END;
$$;

REVOKE ALL ON FUNCTION public.list_internal_customers(text, text, integer, integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.list_internal_customers(text, text, integer, integer) TO authenticated;

CREATE OR REPLACE FUNCTION public.mutate_internal_support_ticket(
  p_ticket_id uuid,
  p_action text,
  p_value text,
  p_message text,
  p_operation_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE actor uuid := auth.uid(); ticket public.support_tickets; v_hash text; prior jsonb; response jsonb;
BEGIN
  IF NOT private.has_internal_permission('support.write', actor) THEN RAISE EXCEPTION 'support_write_not_allowed' USING ERRCODE = '42501'; END IF;
  IF p_action NOT IN ('status', 'priority', 'assignee', 'message', 'note') THEN RAISE EXCEPTION 'invalid_support_action'; END IF;
  v_hash := md5(concat_ws('|', p_ticket_id, p_action, p_value, p_message));
  SELECT result INTO response FROM public.internal_operations WHERE actor_id = actor AND operation_id = p_operation_id AND request_hash = v_hash;
  IF response IS NOT NULL THEN RETURN response; END IF;
  INSERT INTO public.internal_operations(operation_id, actor_id, action, request_hash) VALUES (p_operation_id, actor, 'support.' || p_action, v_hash);
  SELECT * INTO ticket FROM public.support_tickets WHERE id = p_ticket_id FOR UPDATE;
  IF ticket.id IS NULL THEN RAISE EXCEPTION 'ticket_not_found'; END IF;
  prior := jsonb_build_object('status', ticket.status, 'priority', ticket.priority, 'assigned_to', ticket.assigned_to);
  IF p_action = 'status' THEN
    IF p_value NOT IN ('open','in_progress','waiting_customer','resolved','closed') THEN RAISE EXCEPTION 'invalid_status'; END IF;
    UPDATE public.support_tickets SET status = p_value, updated_at = now() WHERE id = p_ticket_id;
  ELSIF p_action = 'priority' THEN
    IF p_value NOT IN ('low','normal','high','critical') THEN RAISE EXCEPTION 'invalid_priority'; END IF;
    UPDATE public.support_tickets SET priority = p_value, updated_at = now() WHERE id = p_ticket_id;
  ELSIF p_action = 'assignee' THEN
    UPDATE public.support_tickets SET assigned_to = nullif(p_value, '')::uuid, updated_at = now() WHERE id = p_ticket_id;
  END IF;
  INSERT INTO public.support_ticket_events(ticket_id, actor_id, event_type, message, metadata)
  VALUES (p_ticket_id, actor, p_action, CASE WHEN p_action IN ('message','note') THEN left(trim(p_message), 5000) ELSE NULL END,
    private.sanitize_internal_metadata(jsonb_build_object('value', left(p_value, 200), 'visibility', CASE WHEN p_action='note' THEN 'internal' ELSE 'shared' END)));
  response := jsonb_build_object('ok', true, 'ticket_id', p_ticket_id, 'action', p_action);
  UPDATE public.internal_operations SET status='succeeded', result=response, completed_at=now() WHERE actor_id=actor AND operation_id=p_operation_id;
  INSERT INTO public.internal_access_events(actor_id, actor_role, action, target_type, target_id, result, metadata)
  VALUES (actor, private.current_internal_role(actor), 'support.' || p_action, 'support_ticket', p_ticket_id::text, 'allowed',
    jsonb_build_object('before', prior, 'value', left(p_value, 200)));
  RETURN response;
END;
$$;
REVOKE ALL ON FUNCTION public.mutate_internal_support_ticket(uuid, text, text, text, uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.mutate_internal_support_ticket(uuid, text, text, text, uuid) TO authenticated;
